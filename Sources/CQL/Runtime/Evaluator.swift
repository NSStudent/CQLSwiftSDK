import Foundation

/// A comment produced by CQL at a position.
public struct GeneratedComment: Hashable, Sendable {
    public let positionID: Int
    public let path: [Int]
    public let text: String
}

/// Evaluates CQL filters against positions of a game.
public final class Evaluator {
    public let program: CQLProgram
    let body: Filter
    /// Whether variation positions are visible to the main loop and tree-walking filters.
    public var searchVariations: Bool
    /// Receives the output of `message` filters.
    public var messageHandler: (String) -> Void = { print($0) }

    // Per-game state
    public private(set) var game: GameTree!
    var current: PositionNode!
    var variables: [String: Value] = [:]
    var persistentVariables: [String: Bool] = [:]  // name → quiet
    var dictionaries: [String: CQLDictionary] = [:]
    var captures: [(text: String, index: Int)?] = []
    var comments: [GeneratedComment] = []
    var tagEdits: [String: String] = [:]
    var removedComments: Set<Int> = []
    /// Best value per sort key for the current game.
    var sortValues: [String: (value: Value, minimum: Bool, documentation: String?)] = [:]
    /// Contextual castling scopes (left, right) for `from`/`to`; `nil` marks a barrier.
    var dashScopes: [DashScope?] = []
    /// Enclosing ⊢ filters being matched.
    var pathStack: [PathState] = []
    var lastPathStart: PositionNode?
    var lastPathEnd: PositionNode?
    /// Positions banned by `nestban`, per ⊢ filter, for the current game.
    var nestBans: [PathFilter: Set<ObjectIdentifier>] = [:]
    var atomicVariables: Set<String> = []
    var iterationGuard = 0
    /// Number of the last game that will be examined (for `lastgamenumber`).
    public var lastGameNumberValue = 0

    public init(program: CQLProgram, searchVariations: Bool? = nil) throws(CQLError) {
        self.program = program
        self.body = try program.body.resolvingTransforms()
        self.searchVariations = searchVariations ?? program.header.variations
    }

    // MARK: - Game lifecycle

    /// Prepares evaluation of a new game.
    public func begin(game: GameTree) {
        self.game = game
        self.current = game.root
        variables = variables.filter { persistentVariables[$0.key] != nil }
        dictionaries = dictionaries.filter { !$0.value.isLocal }
        captures = []
        comments = []
        tagEdits = [:]
        removedComments = []
        sortValues = [:]
        dashScopes = []
        pathStack = []
        lastPathStart = nil
        lastPathEnd = nil
        nestBans = [:]
    }

    /// The positions visited by the main loop, in PGN order.
    public var visiblePositions: [PositionNode] {
        searchVariations ? game.nodes : game.mainline
    }

    /// Evaluates the program body at `position`. Comments generated by a
    /// failed evaluation are discarded.
    public func matches(at position: PositionNode) throws(CQLError) -> Bool {
        current = position
        dashScopes = []
        let mark = comments.count
        let matched = try evaluate(body)?.matches ?? false
        if !matched { comments.removeSubrange(mark...) }
        return matched
    }

    func children(of node: PositionNode) -> [PositionNode] {
        searchVariations ? node.children : Array(node.children.prefix(1))
    }

    var board: BoardState { current.board }

    // MARK: - Evaluation

    /// Evaluates `filter` at the current position; `nil` when it does not match.
    func evaluate(_ filter: Filter) throws(CQLError) -> Value? {
        let mark = comments.count
        let value = try evaluateUnbuffered(filter)
        if value == nil || value?.matches == false, comments.count > mark {
            comments.removeSubrange(mark...)
        }
        return value
    }

    func matches(_ filter: Filter) throws(CQLError) -> Bool {
        try evaluate(filter)?.matches ?? false
    }

    /// Evaluates a set filter (a failing filter denotes the empty set).
    func evaluateSet(_ filter: Filter) throws(CQLError) -> SquareSet {
        switch try evaluate(filter) {
        case .set(let set)?: return set
        case nil: return .empty
        case let other?: throw runtimeError("expected a set of squares, got \(other)")
        }
    }

    func evaluateNumber(_ filter: Filter) throws(CQLError) -> Int? {
        switch try evaluate(filter) {
        case .number(let number)?: return number
        case nil: return nil
        case .set(let set)?: return set.count
        case let other?: throw runtimeError("expected a number, got \(other)")
        }
    }

    func evaluateString(_ filter: Filter) throws(CQLError) -> String? {
        switch try evaluate(filter) {
        case .string(let text)?: return text
        case nil: return nil
        case let other?: throw runtimeError("expected a string, got \(other)")
        }
    }

    func evaluatePosition(_ filter: Filter) throws(CQLError) -> PositionNode? {
        switch try evaluate(filter) {
        case .position(let position)?: return position.node
        case nil: return nil
        case let other?: throw runtimeError("expected a position, got \(other)")
        }
    }

    func runtimeError(_ message: String) -> CQLError {
        CQLError(.runtime, message)
    }

    /// Runs `body` with `node` as the current position.
    func at<T>(_ node: PositionNode, barrier: Bool = true, _ body: () throws(CQLError) -> T) throws(CQLError) -> T {
        let saved = current
        if barrier { dashScopes.append(nil) }
        current = node
        defer {
            current = saved
            if barrier { dashScopes.removeLast() }
        }
        return try body()
    }

    private func evaluateUnbuffered(_ filter: Filter) throws(CQLError) -> Value? {
        switch filter {
        case .number(let number): return .number(number)
        case .string(let text): return .string(text)
        case .pieceDesignator(let designator): return .set(board.evaluate(designator))
        case .variable(let name): return try readVariable(name)
        case .keyword(let name): return try evaluateKeyword(name)

        case .compound(let filters):
            var last: Value = .matched
            for filter in filters {
                guard let value = try evaluate(filter), value.matches else {
                    if case .set = try lastValueType(filters) { return .set(.empty) }
                    return nil
                }
                last = value
            }
            return last

        case .captureGroup(let index):
            guard index < captures.count, let capture = captures[index] else { return nil }
            return .string(capture.text)
        case .captureGroupIndex(let index):
            guard index < captures.count, let capture = captures[index] else { return nil }
            return .number(capture.index)

        case .not(let inner):
            return try matches(inner) ? nil : .matched
        case .negate(let inner):
            return try evaluateNumber(inner).map { .number(-$0) }
        case .complement(let inner):
            return .set(~(try evaluateSet(inner)))
        case .cardinality(let inner):
            if case .variable(let name) = inner, let dictionary = dictionaries[name] {
                return .number(dictionary.count)
            }
            switch try evaluate(inner) {
            case .set(let set)?: return .number(set.count)
            case .string(let text)?: return .number(text.count)
            case nil: return nil
            case let other?: throw runtimeError("# cannot be applied to \(other)")
            }

        case .binary(let op, let lhs, let rhs):
            return try evaluateBinary(op, lhs, rhs)
        case .attackChain(let operands, let reversed):
            return .set(try evaluateAttackChain(operands, reversed: reversed))
        case .at(let positionFilter, let inner):
            guard let node = try evaluatePosition(positionFilter) else { return nil }
            return try at(node) { () throws(CQLError) -> Value? in try evaluate(inner) }
        case .subscript(let target, let start, let end, let isSlice):
            return try evaluateSubscript(target, start, end, isSlice: isSlice)

        case .prefix(let name, let argument):
            return try evaluatePrefix(name, argument)
        case .call(let name, let arguments):
            return try evaluateCall(name, arguments)
        case .direction(let name, let range, let argument):
            return .set(try evaluateDirection(name, range: range, argument))
        case .ray(let direction, let sets, let xray):
            return .set(try evaluateRay(direction: direction, sets, xray: xray))
        case .pin(let from, let through, let to, let role):
            return .set(try evaluatePin(from: from, through: through, to: to, role: role))

        case .assign(let name, let op, let value):
            return try assign(name, op, value)
        case .pieceAssign(let name, let value):
            let set = try evaluateSet(value)
            guard let square = set.single, let id = current.pieceIDs[square] else { return nil }
            variables[name] = .piece(PieceIdentity(id: id))
            return .matched
        case .subscriptAssign(let name, let key, let end, let isSlice, let value):
            return try assignSubscript(name, key: key, end: end, isSlice: isSlice, value: value)
        case .persistent(let quiet, let name, let op, let value):
            if persistentVariables[name] == nil {
                persistentVariables[name] = quiet
                if variables[name] == nil {
                    switch try staticDefault(for: value) {
                    case let initial?: variables[name] = initial
                    case nil: break
                    }
                }
            }
            return try assign(name, op, value)
        case .atomic(let name, let op, let value):
            atomicVariables.insert(name)
            return try assign(name, op, value)
        case .path(let path):
            return try evaluatePath(path)
        case .consecutiveMoves(let quiet, let range, let first, let second):
            return try evaluateConsecutiveMoves(quiet: quiet, range: range, first, second)
        case .unbind(let name, let key):
            if let key {
                guard let keyValue = try evaluate(key) else { return nil }
                dictionaries[name]?.remove(keyValue)
            } else if dictionaries[name] != nil {
                dictionaries[name]?.removeAll()
            } else {
                variables[name] = nil
            }
            return .matched
        case .isBound(let name, let negated):
            let bound = variables[name] != nil || dictionaries[name] != nil
            return bound != negated ? .matched : nil

        case .iterate(let isPiece, let all, let variable, let domain, let body):
            return try evaluateIteration(isPiece: isPiece, all: all, variable: variable, domain: domain, body: body)
        case .iterateDictionary(let variable, let name, let body):
            guard let dictionary = dictionaries[name] else { return nil }
            let saved = variables[variable]
            defer { variables[variable] = saved }
            var matched = false
            for key in dictionary.keys {
                variables[variable] = key
                if try matches(body) { matched = true }
            }
            return matched ? .matched : nil
        case .ifThen(let test, let consequent, let alternative):
            if try matches(test) { return try evaluate(consequent) }
            if let alternative { return try evaluate(alternative) }
            return .matched
        case .loop(let body):
            var count = 0
            while try matches(body) {
                count += 1
                try checkIterations(count)
            }
            return count > 0 ? .matched : nil
        case .whileLoop(let test, let body):
            var count = 0
            while try matches(test) {
                _ = try evaluate(body)
                count += 1
                try checkIterations(count)
            }
            return .matched
        case .whileRegex(let target, let pattern, let body):
            guard let text = try evaluateString(target) else { return nil }
            for match in try regexMatches(pattern, in: text) {
                captures = match
                _ = try evaluate(body)
            }
            return .matched
        case .functionCall(let name, _):
            throw runtimeError("function '\(name)' was not expanded")
        case .dictionaryDeclaration(let name, let local):
            if dictionaries[name] == nil { dictionaries[name] = CQLDictionary(isLocal: local) }
            return .matched
        case .assert(let inner):
            guard try matches(inner) else {
                throw runtimeError("assertion failed (game \(game.gameNumber), position \(current.id))")
            }
            return .matched

        case .tagValue(let field):
            return try evaluateTag(field).map(Value.string)
        case .elo(let color):
            return evaluateElo(color).map(Value.number)
        case .result(let text):
            return game.tags["Result"] == text ? .matched : nil
        case .fenMatch(let pattern):
            return fenMatches(pattern) ? .matched : nil
        case .originalComment(let text):
            return evaluateOriginalComment(text)

        case .dash(let dash, let source):
            return try evaluateDash(dash, source: source)
        case .countMoves(let dash, let source):
            return .number(try matchingMoves(dash, source: source, stopAtFirst: false).count)
        case .find(let quiet, let mode, let backward, let inner):
            return try evaluateFind(quiet: quiet, mode: mode, backward: backward, inner)
        case .echo(let source, let target, let includeSelf, let quiet, let inner):
            return try evaluateEcho(source: source, target: target, includeSelf: includeSelf, quiet: quiet, inner)
        case .child(let index):
            let list = children(of: current)
            var i = 0
            if let index {
                guard let number = try evaluateNumber(index) else { return nil }
                i = number
            }
            guard list.indices.contains(i) else { return nil }
            return .position(PositionRef(list[i]))
        case .position(let index):
            guard let number = try evaluateNumber(index),
                  let node = visiblePositions.first(where: { $0.id == number }) else { return nil }
            return .position(PositionRef(node))

        case .transform:
            throw runtimeError("unresolved transform")
        case .transformOrbit(let elements, let count):
            return try evaluateOrbit(elements, count: count)
        case .notransform(let inner):
            return try evaluate(inner)

        case .comment(let arguments):
            let text = try arguments.map { (argument) throws(CQLError) -> String in try outputText(argument) }.joined()
            comments.append(GeneratedComment(positionID: current.id, path: current.path, text: text))
            return .matched
        case .message(let quiet, let arguments):
            let text = try arguments.map { (argument) throws(CQLError) -> String in try outputText(argument) }.joined()
            if quiet {
                messageHandler(text)
            } else {
                let side = current.sideToMove == .white ? "wtm" : "btm"
                let variation = current.isMainline ? "" : " [\(current.id)]"
                messageHandler("game \(game.gameNumber) move \(current.moveNumber)(\(side))\(variation): \(text)")
            }
            return .matched
        case .sort(let minimum, _, let documentation, let inner):
            guard var value = try evaluate(inner) else { return nil }
            if case .set(let set) = value { value = .number(set.count) }
            let key = documentation ?? "\(inner.hashValue)"
            if let existing = sortValues[key] {
                let better = minimum ? Self.compare(value, existing.value) < 0 : Self.compare(value, existing.value) > 0
                if better { sortValues[key] = (value, minimum, documentation) }
            } else {
                sortValues[key] = (value, minimum, documentation)
            }
            return value
        case .setTag(let name, let value):
            guard let tag = try evaluateString(name), let text = try outputValue(value) else { return nil }
            tagEdits[tag] = text
            return .matched
        }
    }

    func checkIterations(_ count: Int) throws(CQLError) {
        if count > 1_000_000 { throw runtimeError("loop did not terminate after 1000000 iterations") }
    }

    /// Whether the compound's last filter is a set filter (statically approximated).
    private func lastValueType(_ filters: [Filter]) throws(CQLError) -> Value? {
        guard let last = filters.last else { return nil }
        switch last {
        case .pieceDesignator, .attackChain, .direction, .ray, .pin, .complement: return .set(.empty)
        default: return nil
        }
    }

    // MARK: - Variables

    func readVariable(_ name: String) throws(CQLError) -> Value? {
        guard let value = variables[name] else {
            if dictionaries[name] != nil { throw runtimeError("dictionary '\(name)' must be subscripted") }
            throw runtimeError("attempt to access unbound variable \(name)")
        }
        if case .piece(let piece) = value {
            return .set(current.square(ofPiece: piece.id).map { SquareSet(index: $0) } ?? .empty)
        }
        return value
    }

    func assign(_ name: String, _ op: AssignmentOperator, _ valueFilter: Filter) throws(CQLError) -> Value? {
        if case .variable(let source) = valueFilter, case .piece? = variables[source], op == .assign {
            // Copying a piece variable copies its current square set.
        }
        switch op {
        case .assign, .assignIfNonEmpty:
            guard let value = try evaluate(valueFilter) else { return nil }
            switch value {
            case .matched:
                throw runtimeError("cannot assign a filter without a value to \(name)")
            case .set(let set):
                if op == .assignIfNonEmpty, set.isEmpty { return nil }
            default:
                break
            }
            try checkType(name, value)
            variables[name] = value
            return .matched
        default:
            guard let current = variables[name] else { throw runtimeError("attempt to access unbound variable \(name)") }
            guard let operand = try evaluate(valueFilter) else { return nil }
            switch (current, operand) {
            case (.string(let text), .string(let suffix)) where op == .add:
                variables[name] = .string(text + suffix)
            case (.number(let left), _):
                let right: Int
                switch operand {
                case .number(let number): right = number
                case .set(let set): right = set.count
                default: throw runtimeError("\(op.rawValue) needs a numeric right-hand side")
                }
                guard let result = Self.arithmetic(Self.binaryOperator(op), left, right) else { return nil }
                variables[name] = .number(result)
            default:
                throw runtimeError("\(op.rawValue) cannot be applied to \(name)")
            }
            return .matched
        }
    }

    private func checkType(_ name: String, _ value: Value) throws(CQLError) {
        guard let existing = variables[name] else { return }
        if Self.typeTag(existing) != Self.typeTag(value), !(Self.typeTag(existing) == "piece" && Self.typeTag(value) == "set") {
            throw runtimeError("variable \(name) cannot change its type")
        }
    }

    static func typeTag(_ value: Value) -> String {
        switch value {
        case .matched: "logical"
        case .set: "set"
        case .number: "number"
        case .string: "string"
        case .position: "position"
        case .piece: "piece"
        }
    }

    private func staticDefault(for filter: Filter) throws(CQLError) -> Value? {
        var parser = Parser(tokens: [])
        parser.variableTypes = [:]
        switch parser.typeOf(filter) {
        case .number: return .number(0)
        case .string: return .string("")
        case .set: return .set(.empty)
        default: return .number(0)
        }
    }

    static func binaryOperator(_ op: AssignmentOperator) -> BinaryOperator {
        switch op {
        case .add: .add
        case .subtract: .subtract
        case .multiply: .multiply
        case .divide: .divide
        default: .modulo
        }
    }

    static func arithmetic(_ op: BinaryOperator, _ left: Int, _ right: Int) -> Int? {
        switch op {
        case .add: return left &+ right
        case .subtract: return left &- right
        case .multiply: return left &* right
        case .divide: return right == 0 ? nil : left / right
        case .modulo: return right == 0 ? nil : left % right
        default: return nil
        }
    }

    // MARK: - Iteration

    private func evaluateIteration(isPiece: Bool, all: Bool, variable: String, domain: Filter, body: Filter) throws(CQLError) -> Value? {
        let squares = try evaluateSet(domain)
        let saved = variables[variable]
        defer { variables[variable] = saved }
        var result = SquareSet()
        for square in squares {
            if isPiece {
                guard let id = current.pieceIDs[square] else { continue }
                variables[variable] = .piece(PieceIdentity(id: id))
            } else {
                variables[variable] = .set(SquareSet(index: square))
            }
            if try matches(body) {
                result.insert(square)
            } else if all {
                return nil
            }
        }
        return all ? .matched : .set(result)
    }

    // MARK: - Orbits

    private func evaluateOrbit(_ elements: [Filter], count: Bool) throws(CQLError) -> Value? {
        var matched = 0
        var union: SquareSet?
        var best: Value?
        var first: Value?
        for element in elements {
            guard let value = try evaluate(element) else { continue }
            if case .set(let set) = value {
                union = (union ?? .empty) | set
                if set.isEmpty { continue }
            }
            matched += 1
            if first == nil { first = value }
            if case .number = value {
                if best == nil || Self.compare(value, best!) > 0 { best = value }
            }
        }
        if count { return .number(matched) }
        if let union { return .set(union) }
        guard matched > 0 else { return nil }
        return best ?? first
    }

    /// Orders two values of the same kind (numbers numerically, strings lexicographically).
    static func compare(_ lhs: Value, _ rhs: Value) -> Int {
        switch (lhs, rhs) {
        case (.number(let a), .number(let b)): return a < b ? -1 : a == b ? 0 : 1
        case (.string(let a), .string(let b)): return a < b ? -1 : a == b ? 0 : 1
        case (.position(let a), .position(let b)): return a.node.id < b.node.id ? -1 : a.node.id == b.node.id ? 0 : 1
        case (.set(let a), .set(let b)): return a.count < b.count ? -1 : a.count == b.count ? 0 : 1
        default: return 0
        }
    }
}

/// A CQL dictionary with insertion-ordered keys.
struct CQLDictionary {
    var isLocal: Bool
    private(set) var keys: [Value] = []
    private var storage: [Value: Value] = [:]

    init(isLocal: Bool) { self.isLocal = isLocal }

    var count: Int { storage.count }
    subscript(key: Value) -> Value? { storage[key] }

    mutating func set(_ key: Value, _ value: Value) {
        if storage.updateValue(value, forKey: key) == nil { keys.append(key) }
    }

    mutating func remove(_ key: Value) {
        if storage.removeValue(forKey: key) != nil { keys.removeAll { $0 == key } }
    }

    mutating func removeAll() {
        keys = []
        storage = [:]
    }
}
